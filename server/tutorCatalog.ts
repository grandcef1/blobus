/** Ключ персонажа: тот же union, что хранится в sessions.tutor_id. */
export type TutorId =
    "miya" | "oscar" | "luna" | "max" | "alex" | "zoe" | "nova" | "kai" | "lira" | "orion";

/** Геометрия и палитра блобатара: форма, цвет и пропорции, а не текст. */
export interface TutorTraits {
    readonly shape: number;
    readonly hue: number;
    readonly tone: readonly [number, number];
    readonly "eye.gap": number;
    readonly "eye.rx": number;
    readonly "eye.lean": number;
    readonly "body.r": number;
    readonly "body.n": number;
    readonly "body.ratio": number;
}

/** Черты характера: ровно три строки — длину проверяет компилятор, а не глаза. */
export type TutorPersonaTraits = readonly [string, string, string];

export interface TutorPersona {
    /** Три черты, показываются одной строкой через разделитель. */
    readonly traits: TutorPersonaTraits;
    /** Одна строка о стиле преподавания: видна на карточке всегда. */
    readonly teachingStyle: string;
    /** История происхождения: раскрывается по кнопке под описанием. */
    readonly story: string;
}

export interface Tutor {
    readonly id: TutorId;
    readonly name: string;
    readonly traits: TutorTraits;
    readonly persona: TutorPersona;
}

