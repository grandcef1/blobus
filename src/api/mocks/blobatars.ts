// ARCHITECT: мок сессий первой итерации ссылается на старые id репетиторов
// (aria, sophia, oliver). Карта нормализует их в текущие id блобатаров,
// чтобы аватары и имена рисовались везде. Удалить после нормализации sessions.ts.
const LEGACY_BLOBATAR_IDS: Record<string, BlobatarId> = {
    aria: "miya",
    sophia: "luna",
    oliver: "oscar",
};

export function getBlobatarById(id: string): Blobatar | undefined {
    const legacyId = LEGACY_BLOBATAR_IDS[id];
    return MOCK_BLOBATARS.find((blobatar) => blobatar.id === id || blobatar.id === legacyId);
}

// ARCHITECT: режим -> рекомендованные персонажи. Раньше профиль искал репетитора перебором
// производного списка по specialties, из-за чего для части режимов показывался чужой
// персонаж или заглушка. Теперь связь задана один раз в MOCK_LEARNING_MODES.
export function getPersonaByMode(mode: LearningMode): Blobatar[] {
    const modeOption = MOCK_LEARNING_MODES.find((item) => item.id === mode);
    if (!modeOption) return [];

    return modeOption.recommendedRepetitors
        .map((id) => getBlobatarById(id))
        .filter((blobatar): blobatar is Blobatar => blobatar !== undefined);
}

